import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const contractsDir = fileURLToPath(new URL("../contracts", import.meta.url));
const outFile = fileURLToPath(new URL("../shared/src/abi.ts", import.meta.url));

const abi = JSON.parse(
  execSync("forge inspect Monarch abi --json", { cwd: contractsDir }).toString()
);

writeFileSync(
  outFile,
  `// Generated by scripts/export-abi.mjs from contracts/src/Monarch.sol. Run \`pnpm abi\` after changing the contract.\nexport const monarchAbi = ${JSON.stringify(abi, null, 2)} as const;\n`
);
console.log(`Wrote ${abi.length} ABI entries to shared/src/abi.ts`);
